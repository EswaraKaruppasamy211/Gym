const translateText = (value: string, language: Language): string => {
  if (language === 'en') return value
  const leading = value.match(/^\s*/)?.[0] ?? ''
  const trailing = value.match(/\s*$/)?.[0] ?? ''
  const content = value.trim()
  const exact = tamil[content] ?? Object.entries(tamil).find(([key]) => key.toLowerCase() === content.toLowerCase())?.[1]
  if (exact) return `${leading}${exact}${trailing}`

  const statusMatch = content.match(/^(✓\s*)?(Goal|Available time|Experience|Preferred type|Equipment|Recent activity|Recent feedback|Recovery signal):\s*(.*)$/)
  if (statusMatch) {
    const key = statusMatch[2]
    const translatedValue: string = translateText(statusMatch[3], language)
    return `${leading}${statusMatch[1] ?? ''}${tamil[key]}: ${translatedValue}${trailing}`
  }

  const durationMatch = content.match(/^(\d+)\s*min(?:utes?)?$/i)
  if (durationMatch) return `${leading}${durationMatch[1]} நிமிடங்கள்${trailing}`
  const indexMatch = content.match(/^Exercise\s+(\d+)\s+of\s+(\d+)$/)
  if (indexMatch) return `${leading}பயிற்சி ${indexMatch[1]} / ${indexMatch[2]}${trailing}`
  const dayMatch = content.match(/^DAY\s+(\d+)\s*\/\s*30$/)
  if (dayMatch) return `${leading}நாள் ${dayMatch[1]} / 30${trailing}`
  const daysMatch = content.match(/^(\d+)\s+days?$/i)
  if (daysMatch) return `${leading}${daysMatch[1]} நாட்கள்${trailing}`
  const localizedUnits = content
    .replace(/\bminutes?\b/gi, 'நிமிடங்கள்')
    .replace(/\bmins?\b/gi, 'நிமிடங்கள்')
    .replace(/\bseconds?\b/gi, 'விநாடிகள்')
    .replace(/\bsecs?\b/gi, 'விநாடிகள்')
    .replace(/\breps?\b/gi, 'முறைகள்')
    .replace(/\brounds?\b/gi, 'சுற்றுகள்')
    .replace(/\bper side\b/gi, 'ஒவ்வொரு பக்கமும்')
    .replace(/\bper leg\b/gi, 'ஒவ்வொரு காலும்')
    .replace(/\btimed block\b/gi, 'நேரத் தொகுதி')
    .replace(/\bFat burn\b/gi, 'கொழுப்பு எரிப்பு')
    .replace(/\bFull body\b/gi, 'முழு உடல்')
    .replace(/\bweight loss\b/gi, 'எடை குறைப்பு')
    .replace(/\bmuscle building\b/gi, 'தசை வளர்ப்பு')
    .replace(/\bgeneral fitness\b/gi, 'பொது உடற்தகுதி')
    .replace(/\bstrength\b/gi, 'வலிமை')
    .replace(/\bflexibility\b/gi, 'நெகிழ்வுத்தன்மை')
    .replace(/\bendurance\b/gi, 'சகிப்புத்தன்மை')
    .replace(/\bbeginner\b/gi, 'தொடக்கநிலை')
    .replace(/\bintermediate\b/gi, 'இடைநிலை')
    .replace(/\badvanced\b/gi, 'மேம்பட்ட நிலை')
    .replace(/\bmoderate\b/gi, 'மிதமானது')
    .replace(/\beasy\b/gi, 'எளிது')
    .replace(/\bhard\b/gi, 'கடினம்')
    .replace(/\bworkouts?\b/gi, 'உடற்பயிற்சி')
    .replace(/\bsessions?\b/gi, 'பயிற்சி')
    .replace(/\bcompleted\b/gi, 'முடிக்கப்பட்டது')
    .replace(/\bstreak\b/gi, 'தொடர்ச்சி')
    .replace(/\bside\b/gi, 'பக்கம்')
    .replace(/\bleg\b/gi, 'கால்')
    .replace(/\bflow\b/gi, 'பயிற்சி')
    .replace(/\beffort\b/gi, 'முயற்சி')
    .replace(/\bpreference\b/gi, 'விருப்பம்')
    .replace(/\bequipment\b/gi, 'உபகரணங்கள்')
  return localizedUnits === content ? value : `${leading}${localizedUnits}${trailing}`
}

export const translate = (text: string, language: Language) => translateText(text, language)
